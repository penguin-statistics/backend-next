-- drop_reports: 3 indexes instead of 8. What reads drop_reports (internal/repo/drop_report.go unless noted):
--
-- - the global drop and pattern matrices and trends (calcwkr, every batch, per server, over days):
--   reliability = 0 AND server = ? AND created_at in a range [AND stage_id IN (...)]
-- - recent site stats and unique users (created_at >= now() - 24h or a duration), the reject rule reevaluation
--   (service/admin.go, a created_at range), the archive (a day of created_at), GetDropReports (ORDER BY created_at)
-- - personal matrices and queries: account_id = ? AND reliability >= 0 AND server = ? AND created_at in a range
-- - by id: DeleteDropReport, the apply of a reject rule reevaluation (controller/meta/admin.go), report_id = ?
-- - the admin pattern fix (controller/meta/admin.go, generated by hand, run once): pattern_id = ?
--
-- Kept:
-- - drop_reports_pkey (report_id, created_at), in schema.sql: every lookup by report_id.
-- - drop_reports_created_at (created_at): every time range scan above. server is not part of it: CN has ~99% of the
--   reports, so a leading server saves next to nothing for the queries that matter, and the queries without server
--   could not use it.
-- - drop_reports_account_id_created_at (account_id, created_at): personal queries, with the time range as an index
--   condition (it replaces drop_reports_account_id).
--
-- Dropped:
-- - drop_reports_created_at_brin and drop_reports_created_at_brin32: duplicates of the btree on created_at.
-- - drop_reports_stage_id: stage filters always come with a time range, which is the selective part.
-- - drop_reports_reliability: nearly every report has reliability 0, it selects nothing.
-- - drop_reports_pattern_id: only the admin pattern fix filters by it, and a scan of the hot months is fine there.
-- The referenced rows of the foreign keys (accounts, drop_patterns, stages) are never deleted, so the referencing
-- columns need no index for them.
CREATE INDEX drop_reports_created_at ON drop_reports USING btree (created_at);
CREATE INDEX drop_reports_account_id_created_at ON drop_reports USING btree (account_id, created_at);
